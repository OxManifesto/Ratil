import '../constants/app_language.dart';

class AsmaulHusnaEntry {
  final int number;
  final String arabic;
  final String transliteration;
  final String meaning;
  final String? meaningKurdish;
  final String? meaningArabic;

  const AsmaulHusnaEntry({
    required this.number,
    required this.arabic,
    required this.transliteration,
    required this.meaning,
    this.meaningKurdish,
    this.meaningArabic,
  });

  String meaningFor(AppLanguage language) {
    switch (language) {
      case AppLanguage.kurdish:
        return (meaningKurdish != null &&
                meaningKurdish!.trim().isNotEmpty)
            ? meaningKurdish!
            : meaning;
      case AppLanguage.arabic:
        return (meaningArabic != null && meaningArabic!.trim().isNotEmpty)
            ? meaningArabic!
            : meaning;
      case AppLanguage.english:
        return meaning;
    }
  }
}

